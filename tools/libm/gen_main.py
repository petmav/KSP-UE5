"""Entry point of the libm lifter (WP-00L).

  python gen_main.py msvcr120 <msvcr120_clr0400.dll> <out_dir>   -> vs2013_libm_gen.cpp, vs2013_libm_data.inc
  python gen_main.py ucrt     <ucrtbase.dll>         <out_dir>   -> ucrt_libm_gen.cpp,   ucrt_libm_data.inc

Both DLLs ship with Windows (System32). Needs capstone (harness/tools-cache/venv). Output is committed under
core/src/dotnet/; regenerate only when the lifter changes.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_lift as G
from gen_lift import Image, discover, emit

CONFIGS = {
    'msvcr120': dict(
        ns='vs2013', prefix='vs2013_libm', dll_name='msvcr120_clr0400.dll',
        names=['acos', 'asin', 'atan', 'atan2', 'cosh', 'exp', 'log', 'log10', 'pow', 'sinh', 'tan', 'tanh'],
        two=('pow', 'atan2'), ctype='double', header='ksp/dotnet/vs2013_libm.hpp',
        stubs=dict(G.STUBS), fma_rva=0xe91d8, setter='SetFma3', getter='GetFma3'),
    'ucrt': dict(
        ns='ucrt', prefix='ucrt_libm', dll_name='ucrtbase.dll',
        names=['sinf', 'cosf', 'powf'], two=('powf',), ctype='float', header='ksp/dotnet/ucrt_libm.hpp',
        stubs={0x4fbb0: 'StubRet0'}, fma_rva=None,
        # __isa_available (set by the CRT at start-up from CPUID; file image holds 0). >= 2 selects the SSE4.1 code paths.
        patches={0x1384c8: 5}, setter='SetFma3', getter='GetFma3'),
}


def main():
    which, path, out_dir = sys.argv[1:4]
    cfg = CONFIGS[which]
    G.STUBS.clear()
    G.STUBS.update(cfg['stubs'])
    img = Image(path)
    roots = [img.ex[n] for n in cfg['names']]
    funcs = discover(img, roots, cfg['stubs'])
    lf, protos, lines = emit(img, funcs)
    refs = sorted(set(va - img.ib for (_, va, _) in lf.rip_refs))
    open(os.path.join(out_dir, cfg['prefix'] + '_refs.txt'), 'w').write('\n'.join('%x' % r for r in refs))
    # FMA3 flag cell(s): rip-relative dword compared against 0 in the first instructions of an exported function
    fma = cfg['fma_rva']
    if fma is None:
        cands = set()
        for n in cfg['names']:
            e = img.ex[n]
            ins = img.decode(e)
            if ins.mnemonic == 'cmp' and ins.operands[0].type == G.X.X86_OP_MEM:
                cands.add(ins.address + ins.size + ins.operands[0].mem.disp - img.ib)
        assert len(cands) == 1, cands
        fma = cands.pop()
    # ---- data segments: clusters of referenced addresses (+ padding for indexed tables) ----
    pts = sorted(set(refs) | set(lf.disp_refs))
    pts = [r for r in pts if r >= 0x1000 and r != fma]
    clusters = []
    for r in pts:
        if clusters and r - clusters[-1][1] <= 0x2000:
            clusters[-1][1] = r
        else:
            clusters.append([r, r])
    inc = ['// GENERATED by tools/libm/gen_lift.py from %s: the data ranges read by the lifted code.' % cfg['dll_name'], '']
    segs = []
    for i, (lo, hi) in enumerate(clusters):
        lo2 = lo & ~0xf
        hi2 = (hi + 0x400 + 0xf) & ~0xf
        raw = bytearray(img.mem(lo2, hi2 - lo2) or b'')
        for prva, pval in cfg.get('patches', {}).items():
            if lo2 <= prva < lo2 + len(raw): raw[prva - lo2:prva - lo2 + 4] = pval.to_bytes(4, 'little')
        inc.append('alignas(16) static const uint8_t kSeg%d[%d] = {' % (i, len(raw)))
        for k in range(0, len(raw), 32):
            inc.append('    ' + ','.join('0x%02x' % b for b in raw[k:k + 32]) + ',')
        inc.append('};')
        segs.append((img.ib + lo2, len(raw), i))
    inc.append('static const Seg kSegs[] = {')
    for va, n, i in segs:
        inc.append('    {0x%xull, %d, kSeg%d},' % (va, n, i))
    inc.append('};')
    with open(os.path.join(out_dir, cfg['prefix'] + '_data.inc'), 'w', newline=chr(10)) as f:
        f.write(chr(10).join(inc) + chr(10))
    ns, ct = cfg['ns'], cfg['ctype']
    hdr = ['// GENERATED by tools/libm/gen_lift.py from %s (x64) -- do not edit.' % cfg['dll_name'],
           "// Mechanical translation of the CRT's own machine code; see vs2013_lift.hpp. Private project: never distributed.",
           '#include "vs2013_lift.hpp"', '#include "%s"' % cfg['header'], '',
           'namespace ksp::dotnet::%s {' % ns, 'using namespace vs2013::lift;', 'namespace {', '']
    tail = ['#include "%s_data.inc"' % cfg['prefix'], '',
            'bool g_fma3 = true;',
            'const Lib kLib = {kSegs, %d, 0x%xull, &g_fma3};' % (len(segs), img.ib + fma),
            '',
            'double RunD(void (*fn)(Cpu&), double x, double y) {' if ct == 'double' else 'float RunF(void (*fn)(Cpu&), float x, float y) {',
            '    Cpu c;',
            '    std::memset(&c, 0, sizeof c);',
            '    c.lib = &kLib;',
            '    c.mxcsr = 0x1f80;']
    if ct == 'double':
        tail += ['    c.x[0].lo = B(x);', '    c.x[1].lo = B(y);']
    else:
        tail += ['    uint32_t xb, yb;', '    std::memcpy(&xb, &x, 4);', '    std::memcpy(&yb, &y, 4);', '    c.x[0].lo = xb;', '    c.x[1].lo = yb;']
    tail += ['    c.r[RSP] = kStackBase + kStackSize - 128;  // 16-byte aligned before the call pushes the return address',
             '    c.r[RSP] -= 8;',
             '    St(c, c.r[RSP], 0xdeadbeefull, 8);',
             '    fn(c);']
    if ct == 'double':
        tail += ['    return D(c.x[0].lo);']
    else:
        tail += ['    const uint32_t rb = static_cast<uint32_t>(c.x[0].lo);', '    float r;', '    std::memcpy(&r, &rb, 4);', '    return r;']
    tail += ['}', '}  // namespace', '']
    runner = 'RunD' if ct == 'double' else 'RunF'
    for n in cfg['names']:
        if n in cfg['two']:
            tail.append('%s %s(%s x, %s y) { return %s(f_%x, x, y); }' % (ct, n, ct, ct, runner, img.ex[n]))
        else:
            tail.append('%s %s(%s x) { return %s(f_%x, x, 0); }' % (ct, n, ct, runner, img.ex[n]))
    tail += ['', 'void %s(bool on) { g_fma3 = on; }' % cfg['setter'], 'bool %s() { return g_fma3; }' % cfg['getter'], '',
             '}  // namespace ksp::dotnet::%s' % ns, '']
    # g_fma3 / kLib live in the anonymous namespace opened by the header; the setters must be outside it: close early
    body = hdr + protos + [''] + lines
    # move the anonymous-namespace close before the public functions
    out = []
    in_tail_public = False
    with open(os.path.join(out_dir, cfg['prefix'] + '_gen.cpp'), 'w', newline=chr(10)) as f:
        f.write(chr(10).join(body + tail))
    print(which, 'functions', len(funcs), 'insns', sum(len(v[0]) for v in funcs.values()), 'fma flag rva %x' % fma,
          'segments', [(hex(v), n) for v, n, _ in segs], file=sys.stderr)


if __name__ == '__main__':
    main()
