# literals
def f32(v):
    return struct.unpack("<f", struct.pack("<f", v))[0]


def lit_double(v):
    if isinstance(v, str):
        v = {"Infinity": float("inf"), "-Infinity": float("-inf"), "NaN": float("nan")}[v]
    v = float(v)
    if v != v:
        return "std::numeric_limits<double>::quiet_NaN()"
    if v in (float("inf"), float("-inf")):
        return ("-" if v < 0 else "") + "std::numeric_limits<double>::infinity()"
    s = repr(v)
    if "e" not in s and "." not in s and "inf" not in s:
        s += ".0"
    return s


def lit_float(v):
    if isinstance(v, str):
        v = {"Infinity": float("inf"), "-Infinity": float("-inf"), "NaN": float("nan")}[v]
    v = float(v)
    if v != v:
        return "std::numeric_limits<float>::quiet_NaN()"
    if v in (float("inf"), float("-inf")):
        return ("-" if v < 0 else "") + "std::numeric_limits<float>::infinity()"
    assert f32(v) == v, v
    if v == 0.0:
        return "-0.0f" if str(v).startswith("-") else "0.0f"
    for p in range(6, 10):
        s = "%.*g" % (p, v)
        if f32(float(s)) == v:
            break
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def lit_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def cs_literal_to_cpp(t, init):
    """C# field initialiser literal -> C++ (only the simple forms PhysicsGlobals uses for non-serialized fields)."""
    if init is None:
        return {"double": "0.0", "float": "0.0f", "int": "0", "bool": "false"}.get(t, "{}")
    if t == "float":
        x = init.rstrip("f")
        if not re.search(r"[.eE]", x):
            x += ".0"
        return x + "f"
    return init


