def curve_init(c, indent):
    fc = c["fCurve"]
    keys = []
    for k in fc["m_Curve"]:
        keys.append("{%s, %s, %s, %s, %d, %s, %s}" % (lit_float(k["time"]), lit_float(k["value"]), lit_float(k["inSlope"]),
                                                      lit_float(k["outSlope"]), k.get("weightedMode", 0),
                                                      lit_float(k.get("inWeight", 0.0)), lit_float(k.get("outWeight", 0.0))))
    sep = ",\n" + indent + "    "
    body = ("\n" + indent + "    " + sep.join(keys) + "\n" + indent) if keys else ""
    return "PrefabCurve({%s}, %d, %d, %s, %s)" % (body, fc.get("m_PreInfinity", 2), fc.get("m_PostInfinity", 2),
                                                lit_float(c["_minTime"]), lit_float(c["_maxTime"]))


def gen_physics_globals():
    path = os.path.join(CS, "PhysicsGlobals.cs")
    lines, fields, props = parse_fields(path, 74, 2675)
    ser = json.load(open(os.path.join(SER, "physicsglobals.serialized.json"), encoding="utf-8"))["PhysicsGlobals"]
    src_rel = "PhysicsGlobals.cs"

    # ---- members
    out = [HEADER, "// Included inside class ksp::PhysicsGlobals (include/ksp/physics/physics_globals.hpp).\n",
           "// Instance fields: initialised to the level0 prefab values (harness/golden/serialized/physicsglobals.serialized.json,\n",
           "// origin KSP_x64_Data/level0): Unity overwrites every [SerializeField] before any KSP code runs, so the C# constructor\n",
           "// defaults (quoted as `C#:`) never survive in game. Statics keep their C# initialisers.\n\n"]
    for f in fields:
        t, name = f["type"], f["name"]
        cite = "%s:%d" % (src_rel, f["line"])
        if name == "instance":
            out.append("static inline PhysicsGlobals* instance = nullptr;  // %s\n" % cite)
            continue
        if t == "PhysicMaterial":
            p = ser[name]
            out.append("// %s %s: UnityEngine.PhysicMaterial asset (level0 PPtr FileID %d PathID %d); a physics-engine object, not\n"
                       "// data: the shell maps kerbalEVADynamicFriction/StaticFriction/Bounciness/*Combine onto its own material.  %s\n"
                       % (t, name, p["m_FileID"], p["m_PathID"], cite))
            continue
        ct = CPP_TYPE[t]
        if f["const"]:
            out.append("static constexpr %s %s = %s;  // %s\n" % (ct, name, f["init"], cite))
            continue
        if f["static"]:
            if t == "SurfaceCurvesList":
                out.append("static inline SurfaceCurvesList %s{};  // %s (set by Awake)\n" % (name, cite))
            else:
                out.append("static inline %s %s = %s;  // %s\n" % (ct, name, cs_literal_to_cpp(t, f["init"]), cite))
            continue
        csdef = f["init"] if f["init"] not in (None, "<new>") else ("new ..." if f["init"] == "<new>" else "default")
        if name not in ser:
            out.append("%s %s;  // %s (not serialized; C#: %s)\n" % (ct, name, cite, csdef))
            continue
        v = ser[name]
        if t == "double":
            init = lit_double(v)
        elif t == "float":
            init = lit_float(v)
        elif t == "int":
            init = str(int(v))
        elif t == "bool":
            init = "true" if v else "false"
        elif t == "string":
            init = lit_str(v)
        elif t in ENUMS:
            init = "static_cast<%s>(%d)" % (ENUMS[t], int(v))
        elif t == "FloatCurve":
            out.append("FloatCurve %s = %s;  // %s\n" % (name, curve_init(v, ""), cite))
            continue
        elif t == "Gradient":
            keys = ", ".join("Color{%s, %s, %s, %s}" % tuple(lit_float(v["key%d" % i][c]) for c in "rgba") for i in range(8))
            ct_ = ", ".join(str(v["ctime%d" % i]) for i in range(8))
            at_ = ", ".join(str(v["atime%d" % i]) for i in range(8))
            out.append("Gradient %s{{%s},\n    {%s},\n    {%s}, %d, %d, %d};  // %s\n"
                       % (name, keys, ct_, at_, v["m_Mode"], v["m_NumColorKeys"], v["m_NumAlphaKeys"], cite))
            continue
        elif t == "VesselRanges":
            parts = []
            for sit in ("prelaunch", "landed", "splashed", "flying", "subOrbital", "orbit", "escaping"):
                s = v[sit]
                parts.append("    r.%s = {%s, %s, %s, %s};\n" % (sit, lit_float(s["load"]), lit_float(s["unload"]),
                                                                 lit_float(s["pack"]), lit_float(s["unpack"])))
            out.append("VesselRanges %s = [] {  // %s\n    VesselRanges r;\n%s    return r;\n}();\n" % (name, cite, "".join(parts)))
            continue
        elif t == "LiftingSurfaceCurve":
            assert all(not v[c]["fCurve"]["m_Curve"] for c in ("liftCurve", "liftMachCurve", "dragCurve", "dragMachCurve"))
            out.append("std::shared_ptr<LiftingSurfaceCurve> %s = std::make_shared<LiftingSurfaceCurve>();  // %s (prefab: "
                       "empty curves, name \"%s\"; Start sets it to GetLiftingSurfaceCurve(\"BodyLift\"))\n" % (name, cite, v["name"]))
            continue
        else:
            raise SystemExit("unhandled PhysicsGlobals field type %s %s" % (t, name))
        out.append("%s %s = %s;  // %s (C#: %s)\n" % (ct, name, init, cite, csdef))
    write("include/ksp/physics/physics_globals_members.inc", "".join(out))

    # ---- static properties
    out = [HEADER, "// Included inside class ksp::PhysicsGlobals: the C# static properties (PhysicsGlobals.Name -> PhysicsGlobals::Name(),\n",
           "// setter PhysicsGlobals::SetName(v)). Special cases (Instance, KpaToAtmospheres, JointForce, KerbalEVADragCube, AeroDataDisplay,\n",
           "// AeroGUIDisplay) are hand-written in physics_globals.hpp/.cpp.\n\n"]
    special = {"Instance", "KpaToAtmospheres", "JointForce", "KerbalEVADragCube", "AeroDataDisplay", "AeroGUIDisplay"}
    for p in props:
        if p["name"] in special:
            continue
        t = p["type"]
        ct = CPP_TYPE.get(t)
        if ct is None:
            out.append("// %s %s (%s:%d): not ported (Unity type)\n" % (t, p["name"], src_rel, p["line"]))
            continue
        g = p["get"]
        m = re.fullmatch(r"Instance\.(\w+)", g or "")
        byref = t in ("FloatCurve", "Dictionary<string, LiftingSurfaceCurve>", "VesselRanges", "Gradient")
        if m:
            expr = "Instance()->" + m.group(1)
        elif re.fullmatch(r"\w+", g or ""):
            expr = g
        else:
            raise SystemExit("unhandled property " + p["name"])
        rt = ("%s&" % ct) if byref else ct
        out.append("static %s %s() { return %s; }  // %s:%d\n" % (rt, p["name"], expr, src_rel, p["line"]))
        if p["set"]:
            ms = re.fullmatch(r"Instance\.(\w+) = value;", p["set"])
            assert ms and m and ms.group(1) == m.group(1), p
            arg = ("const %s&" % ct) if ct in ("std::string",) or byref else ct
            out.append("static void Set%s(%s value) { Instance()->%s = value; }\n" % (p["name"], arg, ms.group(1)))
    write("include/ksp/physics/physics_globals_properties.inc", "".join(out))

    # ---- LoadDatabase(ConfigNode) and SaveDatabase statement lists
    ftype = {f["name"]: f["type"] for f in fields}
    start = next(i for i, l in enumerate(lines) if l.startswith("\tprivate void LoadDatabase(ConfigNode node)"))
    end = next(i for i in range(start + 1, len(lines)) if lines[i] == "\t}")
    out = [HEADER, "// Body of PhysicsGlobals::LoadDatabase(const ConfigNode& node), PhysicsGlobals.cs:%d-%d, statement for statement.\n"
           "// float/double/int/bool.Parse throw like C# (dotnet::FormatException...), which aborts the load as in KSP.\n" % (start + 1, end + 1)]
    key = cond = None
    i = start + 2
    while i < end:
        l = lines[i].strip()
        m = re.match(r'(?:string )?value = node\.GetValue\("(\w+)"\);$', l)
        if m:
            key = m.group(1)
            i += 1
            continue
        if l in ("if (value != null)", "if (!string.IsNullOrEmpty(value))"):
            cond = "value" if l == "if (value != null)" else "value && !value->empty()"
            i += 1
            continue
        if l in ("{", "}", "try", ""):
            i += 1
            continue
        m = re.match(r"(\w+) = (float|double|int|bool)\.Parse\(value\);$", l)
        if m:
            fn = {"float": "dotnet::ParseSingle", "double": "dotnet::ParseDouble", "int": "dotnet::ParseInt32", "bool": "ParseBool"}[m.group(2)]
            out.append('if (auto value = node.GetValue("%s"); %s) %s = %s(*value);  // %s:%d\n'
                       % (key, cond, m.group(1), fn, src_rel, i + 1))
            i += 1
            continue
        m = re.match(r"(\w+) = value;$", l)
        if m:
            out.append('if (auto value = node.GetValue("%s"); %s) %s = *value;  // %s:%d\n' % (key, cond, m.group(1), src_rel, i + 1))
            i += 1
            continue
        m = re.match(r"(\w+) = \(([\w\.]+)\)Enum\.Parse\(typeof\(([\w\.]+)\), value\);$", l)
        if m:
            et = ENUMS[m.group(2)]
            if lines[i - 2].strip() == "try":
                out.append('if (auto value = node.GetValue("%s"); %s) {  // %s:%d (try/catch: log and keep the old value)\n'
                           '    try {\n        %s = EnumParse<%s>(*value);\n    } catch (const std::exception& ex) {\n'
                           '        log::Error("[PhysicsGlobals]: Failed to parse " + *value + " as VesselTargetModes enum, exception " + ex.what());\n'
                           '    }\n}\n' % (key, cond, src_rel, i + 1, m.group(1), et))
                i += 7
                continue
            out.append('if (auto value = node.GetValue("%s"); %s) %s = EnumParse<%s>(*value);  // %s:%d\n'
                       % (key, cond, m.group(1), et, src_rel, i + 1))
            i += 1
            continue
        m = re.match(r'(?:ConfigNode )?(node\d) = node\.GetNode\("(\w+)"\);$', l)
        if m:
            var, nname = m.group(1), m.group(2)
            body = lines[i + 3].strip()
            mm = re.match(r"(\w+)\.Load\(%s\);$" % var, body) or re.match(r"(LoadLiftingSurfaceCurves)\(%s\);$" % var, body)
            assert mm, body
            if mm.group(1) == "LoadLiftingSurfaceCurves":
                out.append('if (const ConfigNode* n = node.GetNode("%s")) LoadLiftingSurfaceCurves(*n);  // %s:%d\n' % (nname, src_rel, i + 1))
            else:
                out.append('if (const ConfigNode* n = node.GetNode("%s")) %s.Load(*n);  // %s:%d\n' % (nname, mm.group(1), src_rel, i + 1))
            i += 5
            continue
        raise SystemExit("unhandled LoadDatabase statement at %d: %s" % (i + 1, l))
    write("src/physics/physics_globals_load.inc", "".join(out))

    start = next(i for i, l in enumerate(lines) if l.startswith("\tpublic void SaveDatabase()"))
    out = [HEADER, "// SetValue statements of PhysicsGlobals::SaveDatabase(), PhysicsGlobals.cs:%d onwards, in C# order.\n"
           "// `x.ToString()` = the runtime's default formatting (Mono: double G15 with Mono's rounding, float G7); typed SetValue\n"
           "// overloads format double G17 / float G9 / bool True|False (ConfigNode.cs:1644-1799).\n" % (start + 1)]
    for i in range(start, len(lines)):
        l = lines[i].strip()
        if l.startswith("ConfigNode node = configNode.AddNode"):
            break
        m = re.match(r'configNode\.SetValue\("(\w+)", (\w+)(\.ToString\(\)|\.ToStringCached\(\))?, ("(?:[^"\\]|\\.)*"), createIfNotFound: true\);$', l)
        if not m:
            continue
        k, fld, conv, comment = m.groups()
        t = ftype[fld]
        if conv == ".ToString()" and t in ENUMS:
            expr = "std::string(ToString(%s))" % fld
        elif conv == ".ToString()":
            expr = {"double": "dotnet::FormatDoubleG(%s)", "float": "dotnet::FormatSingleG(%s)", "int": "std::to_string(%s)",
                    "bool": "std::string(%s ? \"True\" : \"False\")"}[t] % fld
        elif conv == ".ToStringCached()":
            expr = "std::string(ToString(%s))" % fld
        else:
            expr = {"double": "dotnet::FormatDoubleG(%s, 17)", "float": "dotnet::FormatSingleG(%s, 9)", "int": "std::to_string(%s)",
                    "bool": "std::string(%s ? \"True\" : \"False\")", "string": "%s"}[t] % fld
        out.append('configNode.SetValue("%s", %s, std::optional<std::string>(%s), true);  // %s:%d\n' % (k, expr, comment, src_rel, i + 1))
    write("src/physics/physics_globals_save.inc", "".join(out))

    # ---- reflection table (golden runner / tests / future SaveDatabase tooling)
    out = [HEADER, "// Field table of ksp::PhysicsGlobals in C# declaration order: {name, static, C# type, accessor}.\n"]
    for f in fields:
        t, name = f["type"], f["name"]
        if name == "instance" or t == "PhysicMaterial":
            continue
        kind = {"double": "Double", "float": "Float", "int": "Int", "bool": "Bool", "string": "String", "FloatCurve": "Curve",
                "VesselRanges": "Ranges", "Dictionary<string, LiftingSurfaceCurve>": "LiftingSurfaces"}.get(t, "Enum" if t in ENUMS else "Other")
        tname = t.split(".")[-1] if t in ENUMS else t
        if f["static"] or f["const"]:
            acc = "[](const PhysicsGlobals&) -> const void* { return &PhysicsGlobals::%s; }" % name
        else:
            acc = "[](const PhysicsGlobals& p) -> const void* { return &p.%s; }" % name
        out.append('{"%s", %s, %s, FieldKind::%s, "%s", %s},\n' % (name, "true" if (f["static"] or f["const"]) else "false",
                                                                 "true" if f["const"] else "false", kind, tname, acc))
    write("src/physics/physics_globals_fields.inc", "".join(out))


