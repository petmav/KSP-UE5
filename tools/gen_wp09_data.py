# C# field parser (top-level members of one class)
def parse_fields(path, first=1, last=None):
    lines = open(path, encoding="utf-8-sig").read().replace("\r", "").split("\n")
    fields, props = [], []
    i, n = first - 1, len(lines) if last is None else last
    while i < n:
        l = lines[i]
        m = re.match(r'^\t(private|public|protected|internal) (static )?(const )?([\w\.<>\[\], ]+?) (\w+)( = (.*))?;$', l)
        if m and "(" not in m.group(4):
            fields.append(dict(line=i + 1, static=bool(m.group(2)), const=bool(m.group(3)), type=m.group(4), name=m.group(5),
                               init=m.group(7)))
            i += 1
            continue
        m = re.match(r'^\t(private|public|protected|internal) (static )?([\w\.<>\[\], ]+?) (\w+) = (new .*)$', l)
        if m:
            j, depth = i, l.count("{") - l.count("}")
            while not (depth == 0 and lines[j].rstrip().endswith(";")):
                j += 1
                depth += lines[j].count("{") - lines[j].count("}")
            fields.append(dict(line=i + 1, static=bool(m.group(2)), const=False, type=m.group(3), name=m.group(4), init="<new>"))
            i = j + 1
            continue
        m = re.match(r'^\tpublic static ([\w\.<>\[\], ]+?) (\w+)( => (.*);)?$', l)
        if m:
            if m.group(3):
                props.append(dict(line=i + 1, type=m.group(1), name=m.group(2), get=m.group(4), set=None, raw=None))
                i += 1
                continue
            if i + 1 < n and lines[i + 1] == "\t{":
                j, body = i + 2, []
                while lines[j] != "\t}":
                    body.append(lines[j].strip())
                    j += 1
                text = " ".join(body)
                g = re.search(r"get \{ return (.*?); \}", text)
                s = re.search(r"set \{ (.*?) \}", text)
                props.append(dict(line=i + 1, type=m.group(1), name=m.group(2), get=g.group(1) if g else None,
                                  set=s.group(1) if s else None, raw=text))
                i = j + 1
                continue
        i += 1
    return lines, fields, props


