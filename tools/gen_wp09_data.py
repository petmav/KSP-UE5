           "//     maps and scaled-space mesh/materials/textures (core/data/kerbol_body_assets.json, tools/extract_body_assets.py)\n"
           "// sharedassets9.assets sha256 %s.\n" % root["provenance"]["asset_files"]["sharedassets9.assets"],
           "#include \"ksp/celestial/celestial_system.hpp\"\n#include \"ksp/curves/serialized_float_curve.hpp\"\n\n#include <limits>\n\n"
