def asset_ref(role, d):
    """C++ GameAssetRef initialiser from an extract_body_assets.py entry"""
    m = d.get("map") or {}
    st = d.get("stream") or {}
    width = d.get("width") or m.get("_width") or 0
    height = d.get("height") or m.get("_height") or 0
    fmt = d.get("format") if d.get("format") is not None else (m.get("_bpp") or 0)
    size = st.get("size") or m.get("dataBytes") or 0
    return "GameAssetRef{%s, %s, %d, %s, %s, %d, %d, %d, %s, %d, %d}" % (
        lit_str(role), lit_str(d.get("file", "")), d.get("pathID", 0), lit_str(d.get("type", "")), lit_str(d.get("name", "")),
        width, height, fmt, lit_str(st.get("path", "")), st.get("offset") or 0, size)


