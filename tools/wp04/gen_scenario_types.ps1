<#
.SYNOPSIS
  Regenerates src/save/scenario_types_data.inc: every ScenarioModule subclass with a [KSPScenario] attribute in the
  shipped Assembly-CSharp.dll, in Mono Assembly.GetTypes() order (TypeDef rows), with its createOptions and target
  scenes. Reads decompiled\KSP-dev\KSP_x64_Data\Managed\Assembly-CSharp.dll with the harness's Mono.Cecil (read-only).

  powershell -NoProfile -ExecutionPolicy Bypass -File <core>\tools\wp04\gen_scenario_types.ps1
#>
$ErrorActionPreference = 'Stop'
$core = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$d = $core
while ($d -and -not (Test-Path (Join-Path $d 'harness\compare\compare.py'))) { $d = Split-Path $d -Parent }
if (-not $d) { throw 'project root not found' }
Add-Type -Path (Join-Path $d 'harness\build\KspGolden\Mono.Cecil.dll')
$dll = Join-Path $d 'decompiled\KSP-dev\KSP_x64_Data\Managed\Assembly-CSharp.dll'
$m = [Mono.Cecil.ModuleDefinition]::ReadModule($dll)
$rows = @()
foreach ($t in ($m.GetTypes() | Sort-Object { $_.MetadataToken.RID })) {
    foreach ($a in $t.CustomAttributes) {
        if ($a.AttributeType.Name -ne 'KSPScenario') { continue }
        $opts = [int]$a.ConstructorArguments[0].Value
        $scenes = @()
        foreach ($s in $a.ConstructorArguments[1].Value) { $scenes += [int]$s.Value }
        $rows += ('KSP_SCENARIO_TYPE("{0}", {1}, {{{2}}})  // RID {3}' -f $t.Name, $opts, ($scenes -join ', '), $t.MetadataToken.RID)
    }
}
$out = Join-Path $core 'src\save\scenario_types_data.inc'
$header = @('// GENERATED by tools/wp04/gen_scenario_types.ps1 from the shipped Assembly-CSharp.dll (do not edit): the',
            '// [KSPScenario] ScenarioModule types in Assembly.GetTypes() order: name, ScenarioCreationOptions, target scenes.')
[System.IO.File]::WriteAllLines($out, [string[]]($header + $rows))
"wrote $out ($($rows.Count) types)"
