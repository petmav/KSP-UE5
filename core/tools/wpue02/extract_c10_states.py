"""WP-UE-02: extract KSP's own C10 ascent states (the 'states' table of harness/captures/out2/aero_forces_vessel.json) into the plain CSV
that the pure-C ctest capi.flight_slice reads (C has no JSON parser in this project).  No value is changed: the IEEE bits (hex) of the
capture are copied as they are.  Run:  python -I core/tools/wpue02/extract_c10_states.py  (from the repository root)."""
import hashlib
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parents[3]
src = root / "harness" / "captures" / "out2" / "aero_forces_vessel.json"
dst = root / "core" / "tests" / "data" / "c10_states.csv"
raw = src.read_bytes()
doc = json.loads(raw)
table = next(t for t in doc["tables"] if t["name"] == "states")
col = {c["name"]: i for i, c in enumerate(table["columns"])}
lines = [
    "# origin: harness/captures/out2/aero_forces_vessel.json table 'states' (KSP 1.12.5 in-game capture C10)",
    "# sha256 of the origin: " + hashlib.sha256(raw).hexdigest(),
    "# generated by core/tools/wpue02/extract_c10_states.py; hex = the IEEE-754 bits of the capture's double",
    "craft,state,frame,altitude_hex,spd_hex,mach_hex",
]
for r in table["rows"]:
    lines.append(",".join([r[col["craft"]], r[col["state"]], str(r[col["frame"]]), r[col["altitude_hex"]], r[col["spd_hex"]], r[col["mach_hex"]]]))
dst.write_text("\n".join(lines) + "\n", newline="\n")
print("wrote", dst, len(lines) - 4, "states")
