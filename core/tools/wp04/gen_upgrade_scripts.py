"""Generate src/save/upgrade_scripts_data.inc from the decompiled SaveUpgradePipeline scripts.

Reads decompiled/KSP-Decompiled/Assembly-CSharp/SaveUpgradePipeline/*.cs (read-only) and emits one descriptor per
PartReplace / PartOffset / ModuleReplace script (attribute, Name, Description, versions, Setup values) plus the
discovery order of all 40 scripts (TypeDef order of the shipped Assembly-CSharp.dll = case-insensitive file name
order, verified with Mono.Cecil). Run: python -I tools/wp04/gen_upgrade_scripts.py <core dir>
"""
import os, re, sys

core = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else '.')
root = core
while root and not os.path.exists(os.path.join(root, 'harness', 'compare', 'compare.py')):
    parent = os.path.dirname(root)
    if parent == root:
        raise SystemExit('project root not found')
    root = parent
src = os.path.join(root, 'decompiled', 'KSP-Decompiled', 'Assembly-CSharp', 'SaveUpgradePipeline')

def cs_float(tok):
    tok = tok.strip()
    assert tok.endswith('f'), tok
    v = tok[:-1]
    if '.' not in v and 'E' not in v and 'e' not in v:
        v += '.0'
    return v + 'f'

def vec(expr):
    if expr.strip() == 'Vector3.zero':
        return 'V3(0.0f, 0.0f, 0.0f)'
    m = re.fullmatch(r'new Vector3\(([^,]+),([^,]+),([^)]+)\)', expr.strip())
    assert m, expr
    return 'V3(%s, %s, %s)' % tuple(cs_float(x) for x in m.groups())

def quat(expr):
    expr = expr.strip()
    if expr == 'Quaternion.identity':
        return 'Quaternionf::identity()'
    parts = [p.strip() for p in expr.split(' * ')]
    out = []
    for p in parts:
        m = re.fullmatch(r'Quaternion\.AngleAxis\(([^,]+), Vector3\.(up|right|forward)\)', p)
        assert m, p
        out.append('UnityNative::AngleAxis(%s, Vector3f::%s())' % (cs_float(m.group(1)), m.group(2)))
    return ' * '.join(out)

def cs_string(s):
    return '"' + s.replace(chr(92), chr(92) * 2) + '"'

files = sorted([f for f in os.listdir(src) if f.endswith('.cs')], key=str.lower)
scripts = []
for f in files:
    text = open(os.path.join(src, f), encoding='utf-8-sig').read()
    attr = re.search(r'\[UpgradeModule\((.*?)\)\]', text)
    if not attr:
        continue
    cls = re.search(r'public class (\w+) : (\w+)', text)
    name, base = cls.group(1), cls.group(2)
    line = text[:cls.start()].count('\n') + 1
    a = attr.group(1)
    ctx = a.split(',')[0].strip()
    sfs = re.search(r'sfsNodeUrl = "([^"]*)"', a)
    craft = re.search(r'craftNodeUrl = "([^"]*)"', a)
    def prop(p):
        m = re.search(r'public override (?:string|Version) ' + p + r' => (.*?);\n', text)
        return m.group(1).strip()
    def version(expr):
        m = re.fullmatch(r'new Version\((\d+), (\d+), (\d+)\)', expr)
        return 'dotnet::Version(%s, %s, %s)' % m.groups()
    d = dict(cls=name, base=base, file=f, line=line,
             ctx=' | '.join('LoadContext::' + c.split('.')[1] for c in ctx.split('|')),
             sfs=sfs.group(1) if sfs else None, craft=craft.group(1) if craft else None,
             title=prop('Name'), desc=prop('Description'),
             earliest=version(prop('EarliestCompatibleVersion')), target=version(prop('TargetVersion')))
    if base in ('PartReplace', 'PartOffset', 'ModuleReplace'):
        body = re.search(r'protected override void Setup\((.*?)\)\s*\{(.*?)\n\t\t\}', text, re.S).group(2) + chr(10)
        def assign(var):
            m = re.search(r'\b' + var + r' = (.*?);\n', body, re.S)
            return m.group(1).strip() if m else None
        if base == 'ModuleReplace':
            d['old'] = assign('oldName')
            d['new'] = assign('newName')
        else:
            d['pName'] = assign('pName')
            d['posOffset'] = vec(assign('posOffset'))
            d['rotOffset'] = quat(assign('rotOffset'))
        if base == 'PartReplace':
            d['replacement'] = assign('replacementPartName')
            d['refTransform'] = assign('refTransformName')
            d['childPos'] = vec(assign('childPosOffset'))
            d['att0'] = vec(assign('att0Offset'))
            offs = []
            for m in re.finditer(r'id = "([^"]*)",\s*offset = (new Vector3\([^)]*\))', body):
                offs.append('AN("%s", %s)' % (m.group(1), vec(m.group(2))))
            d['attN'] = offs
    scripts.append(d)

assert len(scripts) == 40, len(scripts)
out = []
out.append('// GENERATED by tools/wp04/gen_upgrade_scripts.py from decompiled/KSP-Decompiled/Assembly-CSharp/SaveUpgradePipeline')
out.append('// (do not edit). One entry per stock upgrade script, in discovery order (TypeDef order of the shipped')
out.append('// Assembly-CSharp.dll). Kind: R = PartReplace, O = PartOffset, M = ModuleReplace, C = custom class.')
out.append('// clang-format off')
for d in scripts:
    kind = {'PartReplace': 'R', 'PartOffset': 'O', 'ModuleReplace': 'M'}.get(d['base'], 'C')
    head = 'KSP_UPGRADE_SCRIPT(%s, %s, "SaveUpgradePipeline/%s:%d", %s, %s, %s, %s, %s, %s, %s' % (
        kind, d['cls'], d['file'], d['line'], d['ctx'],
        cs_string(d['sfs']) if d['sfs'] is not None else 'nullptr',
        cs_string(d['craft']) if d['craft'] is not None else 'nullptr',
        d['title'], d['desc'], d['earliest'], d['target'])
    if kind == 'R':
        head += ',\n    %s, %s, %s, %s, %s, %s, %s, %s%s)' % (
            d['pName'], d['replacement'], d['refTransform'], d['posOffset'], d['rotOffset'], d['childPos'],
            d['att0'], 'nullptr', ''.join(', ' + x for x in d['attN']))
    elif kind == 'O':
        head += ',\n    %s, nullptr, nullptr, %s, %s, V3(0.0f, 0.0f, 0.0f), V3(0.0f, 0.0f, 0.0f), nullptr)' % (
            d['pName'], d['posOffset'], d['rotOffset'])
    elif kind == 'M':
        head += ',\n    %s, %s, nullptr, V3(0.0f, 0.0f, 0.0f), Quaternionf::identity(), V3(0.0f, 0.0f, 0.0f), V3(0.0f, 0.0f, 0.0f), nullptr)' % (
            d['old'], d['new'])
    else:
        head += ',\n    nullptr, nullptr, nullptr, V3(0.0f, 0.0f, 0.0f), Quaternionf::identity(), V3(0.0f, 0.0f, 0.0f), V3(0.0f, 0.0f, 0.0f), nullptr)'
    out.append(head)
out.append('// clang-format on')
dst = os.path.join(core, 'src', 'save', 'upgrade_scripts_data.inc')
open(dst, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('wrote', dst, len(scripts), 'scripts')
