"""Generate include/ksp/modules/stageable_classes.inc: the PartModule classes whose ReflectedAttributes.isStageable is true.

    python -I tools/wp16/gen_stageable.py <core dir>

PartModule.ReflectedAttributes (PartModule.cs:27-50): `isStageable` is true when `moduleType.GetMethods(Instance | Public)` contains a
method named "OnActive" whose DeclaringType is not PartModule, i.e. the class or one of its base classes (below PartModule) declares
a public OnActive. This script finds the classes that DECLARE `public ... void OnActive()` (same class discovery as
tools/wp05/gen_module_schema.py) and the C++ side (ModuleClassIsStageable) walks the base chain. Regenerate, never hand-edit.
    KSP_STAGEABLE(cls, "file", line)
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "wp05"))
import gen_module_schema as g  # noqa: E402

ONACTIVE = re.compile(r"^\s*public\s+(?:(?:override|virtual|new|sealed)\s+)*void\s+OnActive\s*\(\s*\)")


def main(core):
    p = os.path.abspath(core)
    root = None
    for _ in range(10):
        cand = os.path.join(p, "decompiled", "KSP-Decompiled", "Assembly-CSharp")
        if os.path.isdir(cand):
            root = cand
            break
        p = os.path.dirname(p)
    if root is None:
        raise SystemExit("decompiled/KSP-Decompiled/Assembly-CSharp not found")
    classes = [c for c in g.scan(root) if c["kind"] == "class"]
    by_name = {}
    for c in classes:
        by_name.setdefault(c["name"], []).append(c)

    def derives(c, root_name, seen=None):
        seen = seen or set()
        if c["name"] == root_name:
            return True
        b = c["base"]
        if not b or b in seen:
            return False
        seen.add(b)
        return any(derives(bc, root_name, seen) for bc in by_name.get(b, []))

    mods = [c for c in classes if derives(c, "PartModule")]
    by_file = {}
    for c in classes:
        by_file.setdefault(c["file"], []).append(c)
    out = ["// Generated by tools/wp16/gen_stageable.py from decompiled/KSP-Decompiled/Assembly-CSharp. Do not edit.",
           "// KSP_STAGEABLE(cls, file, line): the class declares `public ... void OnActive()` (PartModule.cs:27 ReflectedAttributes)"]
    n = 0
    for c in mods:
        if c["name"] == "PartModule":
            continue
        lines = open(os.path.join(root, c["file"]), encoding="utf-8-sig", errors="replace").read().splitlines()
        # the next class of the file that is not nested in this one bounds the body (ModuleDecouple declares a nested class first)
        starts = sorted(x["line"] for x in by_file[c["file"]] if not x["full"].startswith(c["full"] + "."))
        nxt = [s for s in starts if s > c["line"]]
        end = nxt[0] - 1 if nxt else len(lines)
        for ln in range(c["line"], end + 1):
            if ONACTIVE.match(lines[ln - 1]):
                out.append('KSP_STAGEABLE("%s", "%s", %d)' % (c["name"], c["file"], ln))
                n += 1
                break
    path = os.path.join(core, "include", "ksp", "modules", "stageable_classes.inc")
    with open(path, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("module classes:", len(mods), "declaring OnActive:", n)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
