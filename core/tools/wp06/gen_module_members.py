"""Generate include/ksp/modules/module_members.inc: the attribute data BaseFieldList / BaseEventList / BaseActionList read
by reflection, for every PartModule, ScenarioModule and VesselModule class of Assembly-CSharp.

    python -I tools/wp06/gen_module_members.py <core dir>

For each class (same discovery as tools/wp05/gen_module_schema.py, which this script imports):
    KSP_MEMBER_FIELD(cls, full, "field", isAxis, "KSPField/KSPAxisField attribute arguments")
    KSP_MEMBER_UI(cls, full, "field", "UI_FloatRange", "UI_Control attribute arguments")
    KSP_MEMBER_EVENT(cls, full, "method", hasDetails, isVirtual, "KSPEvent arguments", line)
    KSP_MEMBER_ACTION(cls, full, "method", isVirtual, "KSPAction arguments (positional + named)", line)
and for the UI_Control tree (UI_*.cs):
    KSP_UI_CLASS("UI_FloatRange", "UI_Control", "file", line)
    KSP_UI_FIELD("UI_FloatRange", "minValue", "float", "initializer")
Attribute argument text is the raw C# text between the parentheses; kspcore evaluates it with its C# constant-expression
evaluator (ksp::cs::ParseAttributeArguments). Regenerate, never hand-edit.
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "wp05"))
import gen_module_schema as g  # noqa: E402


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def raw_attrs(lines, ln):
    """Raw attribute lines stacked directly above source line `ln` (1-based), top to bottom."""
    out = []
    i = ln - 2
    while i >= 0 and lines[i].strip().startswith("["):
        out.append(lines[i].strip())
        i -= 1
    return list(reversed(out))


def attr_args(a, names):
    m = re.match(r"^\[(%s)\b(?:\((.*)\))?\]$" % "|".join(names), a)
    if not m:
        return None
    return m.group(1), (m.group(2) or "").strip()


def main(core):
    p = os.path.abspath(core)
    root = None
    for _ in range(10):
        cand = os.path.join(p, "decompiled", "KSP-Decompiled", "Assembly-CSharp")
        if os.path.isdir(cand):
            root = cand
            break
        p = os.path.dirname(p)
    if root is None:
        raise SystemExit("decompiled/KSP-Decompiled/Assembly-CSharp not found")
    allc = g.scan(root)
    classes = [c for c in allc if c["kind"] == "class"]
    by_name = {}
    for c in classes:
        by_name.setdefault(c["name"], []).append(c)

    def derives(c, rootName, seen=None):
        seen = seen or set()
        if c["name"] == rootName and c["full"] == rootName:
            return True
        b = c["base"]
        if not b or b in seen:
            return False
        seen.add(b)
        return any(derives(bc, rootName, seen) for bc in by_name.get(b, []))

    hosts = [c for c in classes if derives(c, "PartModule") or derives(c, "ScenarioModule") or derives(c, "VesselModule")]
    cache = {}

    def file_lines(rel):
        if rel not in cache:
            cache[rel] = open(os.path.join(root, rel), encoding="utf-8-sig", errors="replace").read().splitlines()
        return cache[rel]

    out = ["// Generated by tools/wp06/gen_module_members.py from decompiled/KSP-Decompiled/Assembly-CSharp. Do not edit.",
           "// KSP_MEMBER_FIELD(cls, full, field, isAxis, args)  KSP_MEMBER_UI(cls, full, field, uiType, args)",
           "// KSP_MEMBER_EVENT(cls, full, method, hasDetails, isVirtual, args, line)",
           "// KSP_MEMBER_ACTION(cls, full, method, isVirtual, args, line)",
           "// KSP_UI_CLASS(name, base, file, line)  KSP_UI_FIELD(class, field, csType, initializer)"]
    nf = nu = ne = na = 0
    for c in hosts:
        lines = file_lines(c["file"])
        cls, full = esc(c["name"]), esc(c["full"])
        for (access, mods, typ, name, init, is_prop), attrs, ln in c["members"]:
            if "static" in mods or "const" in mods:
                continue
            raws = raw_attrs(lines, ln)
            fld = None
            for a in raws:
                r = attr_args(a, ["KSPField", "KSPAxisField"])
                if r:
                    fld = r
            if fld is None:
                continue
            out.append('KSP_MEMBER_FIELD("%s", "%s", "%s", %s, "%s")' % (
                cls, full, esc(name), "true" if fld[0] == "KSPAxisField" else "false", esc(fld[1])))
            nf += 1
            for a in raws:
                m = re.match(r"^\[(UI_\w+)\b(?:\((.*)\))?\]$", a)
                if m:
                    out.append('KSP_MEMBER_UI("%s", "%s", "%s", "%s", "%s")' % (cls, full, esc(name), m.group(1),
                                                                           esc((m.group(2) or "").strip())))
                    nu += 1
        for sig, attrs, ln in c["methods"]:
            raws = raw_attrs(lines, ln)
            raw_sig = lines[ln - 1].strip()
            m = re.match(r"^(?:(?:public|private|protected|internal|virtual|override|static|new|sealed|abstract)\s+)*"
                         r"[\w<>\[\],.?]+\s+(\w+)\s*\((.*)\)\s*$", raw_sig)
            if not m:
                continue
            mname, params = m.group(1), m.group(2)
            virt = bool(re.search(r"\b(virtual|override)\b", raw_sig))
            for a in raws:
                r = attr_args(a, ["KSPEvent"])
                if r:
                    nparams = 0 if not params.strip() else len(params.split(","))
                    if nparams == 0:
                        details = "false"
                    elif nparams == 1 and params.strip().startswith("BaseEventDetails"):
                        details = "true"
                    else:
                        continue  # BaseEventList.ReflectedData ignores other signatures
                    out.append('KSP_MEMBER_EVENT("%s", "%s", "%s", %s, %s, "%s", %d)' % (
                        cls, full, esc(mname), details, "true" if virt else "false", esc(r[1]), ln))
                    ne += 1
                r = attr_args(a, ["KSPAction"])
                if r:
                    out.append('KSP_MEMBER_ACTION("%s", "%s", "%s", %s, "%s", %d)' % (
                        cls, full, esc(mname), "true" if virt else "false", esc(r[1]), ln))
                    na += 1
    # UI_Control tree
    ui = [c for c in classes if c["name"].startswith("UI_") and c["file"].startswith("UI_")]
    for c in ui:
        lines = file_lines(c["file"])
        out.append('KSP_UI_CLASS("%s", "%s", "%s", %d)' % (c["name"], c["base"] or "", c["file"], c["line"]))
        for (access, mods, typ, name, init, is_prop), attrs, ln in c["members"]:
            if access != "public" or "static" in mods or "const" in mods or is_prop:
                continue
            if init:
                mm = re.search(r"\b%s\s*=\s*(.*?);\s*(//.*)?$" % re.escape(name), lines[ln - 1])
                if mm:
                    init = mm.group(1).strip()
            out.append('KSP_UI_FIELD("%s", "%s", "%s", "%s")' % (c["name"], name, esc(typ), esc(init)))
    # enums the attribute arguments use (UI_Scene.cs; KSPActionGroup / KSPAxisGroup come from module_schema.inc)
    out.append("// KSP_MEMBER_ENUM(enumName, isFlags, file, line)  KSP_MEMBER_ENUM_VALUE(enumName, member, value)")
    for en in ("UI_Scene",):
        f = en + ".cs"
        lines = file_lines(f)
        ln = next(i for i, l in enumerate(lines, 1) if re.match(r"^\s*public enum %s\b" % en, l))
        flags = "[Flags]" in lines[ln - 2]
        out.append('KSP_MEMBER_ENUM("%s", %s, "%s", %d)' % (en, "true" if flags else "false", f, ln))
        val = -1
        for l2 in lines[ln + 1:]:
            t = l2.split("//")[0].strip()
            if t.startswith("}"):
                break
            if not t or t == "{" or t.startswith("["):
                continue
            t = t.rstrip(",")
            if "=" in t:
                n, v = [x.strip() for x in t.split("=", 1)]
                val = int(v, 0)
            else:
                n = t
                val += 1
            out.append('KSP_MEMBER_ENUM_VALUE("%s", "%s", %d)' % (en, n, val))
    path = os.path.join(core, "include", "ksp", "modules", "module_members.inc")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("classes:", len(hosts), "fields:", nf, "ui attrs:", nu, "events:", ne, "actions:", na, "UI classes:", len(ui))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
