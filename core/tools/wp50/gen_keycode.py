"""Generates include/ksp/input/keycode.hpp (UnityEngine.KeyCode, Unity 2019.4 CoreModule decompile) and
include/ksp/input/control_types.hpp (ControlTypes.cs).

Usage: python -I tools/wp50/gen_keycode.py <core dir>
Spec: decompiled/KSP-Decompiled/Unity/UnityEngine.CoreModule/UnityEngine/KeyCode.cs and
decompiled/KSP-Decompiled/Assembly-CSharp/ControlTypes.cs. Declaration order is kept: Enum.ToString / Enum.Parse of
ksp::dotnet read EnumTraits in that order.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
CANDIDATES = [os.path.join(ROOT, 'decompiled'), os.path.join('C:' + os.sep, 'Projects', 'KSP-UE5', 'decompiled')]


def find(rel):
    for c in CANDIDATES:
        p = os.path.join(c, 'KSP-Decompiled', rel)
        if os.path.exists(p):
            return p
    raise SystemExit('spec not found: ' + rel)


def write(core, name, lines):
    path = os.path.join(core, 'include', 'ksp', 'input', name)
    with open(path, 'w', newline='\n') as f:
        f.write('\n'.join(lines))
    print(path)


def gen_keycode(core):
    src = find(os.path.join('Unity', 'UnityEngine.CoreModule', 'UnityEngine', 'KeyCode.cs'))
    members = []
    for line in open(src, encoding='utf-8-sig').read().splitlines():
        m = re.match(r'\s*(\w+)\s*=\s*(-?\d+),?\s*$', line)
        if m:
            members.append((m.group(1), int(m.group(2))))
    out = ['// GENERATED by tools/wp50/gen_keycode.py from decompiled/KSP-Decompiled/Unity/UnityEngine.CoreModule/UnityEngine/KeyCode.cs',
           '// -- do not edit. UnityEngine.KeyCode (%d members, declaration order).' % len(members),
           '#pragma once', '', '#include "ksp/dotnet/enum.hpp"', '', 'namespace ksp {', '', 'enum class KeyCode : int {']
    out += ['    %s = %d,' % (n, v) for n, v in members]
    out += ['};', '', '}  // namespace ksp', '', 'template <>', 'struct ksp::dotnet::EnumTraits<ksp::KeyCode> {',
            '    static constexpr bool flags = false;', '    static constexpr EnumMember<ksp::KeyCode> members[] = {']
    out += ['        {ksp::KeyCode::%s, "%s"},' % (n, n) for n, v in members]
    out += ['    };', '};', '']
    write(core, 'keycode.hpp', out)


def gen_control_types(core):
    src = find(os.path.join('Assembly-CSharp', 'ControlTypes.cs'))
    members = []
    for line in open(src, encoding='utf-8-sig').read().splitlines():
        m = re.match(r'\s*(\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)uL,?\s*$', line)
        if m:
            members.append((m.group(1), int(m.group(2), 0)))
    out = ['// GENERATED by tools/wp50/gen_keycode.py from decompiled/KSP-Decompiled/Assembly-CSharp/ControlTypes.cs -- do not edit.',
           '// [Flags] enum ControlTypes : ulong (%d members, declaration order).' % len(members),
           '#pragma once', '', '#include <cstdint>', '', '#include "ksp/dotnet/enum.hpp"', '', 'namespace ksp {', '',
           'enum class ControlTypes : uint64_t {']
    out += ['    %s = 0x%XULL,' % (n, v) for n, v in members]
    out += ['};', '']
    for op in ('|', '&', '^'):
        out.append('constexpr ControlTypes operator%s(ControlTypes a, ControlTypes b) { return static_cast<ControlTypes>('
                   'static_cast<uint64_t>(a) %s static_cast<uint64_t>(b)); }' % (op, op))
    out += ['constexpr ControlTypes operator~(ControlTypes a) { return static_cast<ControlTypes>(~static_cast<uint64_t>(a)); }',
            'constexpr ControlTypes& operator|=(ControlTypes& a, ControlTypes b) { return a = a | b; }',
            'constexpr ControlTypes& operator&=(ControlTypes& a, ControlTypes b) { return a = a & b; }',
            '', '}  // namespace ksp', '', 'template <>', 'struct ksp::dotnet::EnumTraits<ksp::ControlTypes> {',
            '    static constexpr bool flags = true;', '    static constexpr EnumMember<ksp::ControlTypes> members[] = {']
    out += ['        {ksp::ControlTypes::%s, "%s"},' % (n, n) for n, v in members]
    out += ['    };', '};', '']
    write(core, 'control_types.hpp', out)


gen_keycode(sys.argv[1])
gen_control_types(sys.argv[1])
