#!/usr/bin/env python3
"""WP-38 slice 3: generate the mechanical part of FinePrint.ContractDefs from the decompiled C#.

Input : Assembly-CSharp/FinePrint/ContractDefs.cs (read only)
Output: include/ksp/fineprint/contract_defs_members.inc  (the nested static classes with their C# initialisers)
        src/fineprint/contract_defs_gen.cpp              (CreateDefaultConfig, AddSurveyDefinitions, AddPartRequests, AddResourceRequests,
                                                          AddCrewRequests, LoadConfig, ResetToDefaults and the (section, sub, key) -> member registry)

The generator is a line transliterator: every statement of the six functions is one of a handful of C# forms (ConfigNode.AddNode /
AddValue, GetNode, SystemUtilities.LoadNode, if (x != null), IsExpansionInstalled); anything else aborts. The result is regenerated, never
hand-edited. Usage: python -I gen_contract_defs.py <Assembly-CSharp dir> <core dir>
"""
import os
import re
import sys

cs_root, core = sys.argv[1], sys.argv[2]
SRC = os.path.join(cs_root, "FinePrint", "ContractDefs.cs")
lines = [l.rstrip("\r") for l in open(SRC, encoding="utf-8-sig").read().split("\n")]

STR = r'"(?:[^"\\]|\\.)*"'
CPPT = {"float": "float", "int": "int", "bool": "bool", "double": "double", "string": "std::string"}


def find(sig):
    for i, l in enumerate(lines):
        if sig in l:
            return i
    raise SystemExit("missing " + sig)


def lit(ctype, v):
    if ctype == "string":
        return v if v else '""'
    if v is None:
        return {"float": "0.0f", "int": "0", "bool": "false", "double": "0.0"}[ctype]
    if ctype == "float":
        v = v.rstrip("f")
        if "." not in v and "e" not in v.lower():
            v += ".0"
        return v + "f"
    if ctype == "double":
        return v if ("." in v or "e" in v.lower()) else v + ".0"
    return v


# ------------------------------------------------------------------ member classes
start = find("public class ContractDefs : MonoBehaviour") + 2
end = find("public static ConfigNode config;")
out = []
resets = []  # (path, literal)
stack = []
for l in lines[start:end]:
    s = l.strip()
    if not s or s == "{":
        continue
    ind = "    " * (len(stack) + 1)
    m = re.match(r"public static class (\w+)$", s)
    if m:
        out.append(ind + "struct %s {" % m.group(1))
        stack.append(m.group(1))
        continue
    if s == "}":
        stack.pop()
        out.append("    " * (len(stack) + 1) + "};")
        continue
    m = re.match(r"public static (int|float|bool|double|string) (\w+)(?: = (.+))?;$", s)
    if not m:
        raise SystemExit("unexpected member line: " + s)
    ctype, name, init = m.groups()
    out.append(ind + "static inline %s %s = %s;" % (CPPT[ctype], name, lit(ctype, init)))
    resets.append(("::".join(stack + [name]), lit(ctype, init)))
assert not stack, stack

tl_start = find("public static ConfigNode config;")
tl_end = find("public static PreBuiltCraft PreBuiltCraftDefs;")
for l in lines[tl_start:tl_end]:
    m = re.match(r"\s*public static (int|float|bool|double|string) (\w+)(?: = (.+))?;$", l)
    if m:
        ctype, name, init = m.groups()
        out.append("    static inline %s %s = %s;" % (CPPT[ctype], name, lit(ctype, init)))
        resets.append((name, lit(ctype, init)))
open(os.path.join(core, "include", "ksp", "fineprint", "contract_defs_members.inc"), "w", encoding="utf-8", newline="\n").write(
    "// GENERATED by tools/wp38c/gen_contract_defs.py from FinePrint/ContractDefs.cs:13-1337 (the static members with their C# initialisers). Do not edit.\n"
    + "\n".join(out) + "\n")


# ------------------------------------------------------------------ statement transliteration
def path_cpp(p):
    return p.replace(".", "::")


def tr_expr(e):
    e = e.strip()
    e = re.sub(r"^value: ", "", e)
    if re.fullmatch(STR, e):
        return "std::string(" + e + ")"
    if re.fullmatch(r"-?[0-9]+", e) or e in ("true", "false"):
        return e
    if re.fullmatch(r"-?[0-9]+\.[0-9]+", e):
        return e
    if re.fullmatch(r"-?[0-9.]+f", e):
        return lit("float", e)
    if re.fullmatch(r"[A-Za-z_][\w.]*", e):
        return path_cpp(e)
    raise SystemExit("expr? " + e)


node_path = {"config": ("", "")}  # C# variable -> (section, sub)
serenity_block = [False]
registry = []  # (section, sub, key, path, serenity)
depth_stack = []


def tr_stmt(s, kind, ctx):
    m = re.fullmatch(r"ConfigNode (\w+) = null;", s)
    if m:
        return "ConfigNode* %s = nullptr;" % m.group(1)
    if s == "config = new ConfigNode();":
        return "NodePtr root = std::make_shared<ConfigNode>();"
    m = re.fullmatch(r"ConfigNode configNode = config\.AddNode\(new ConfigNode\((%s), (%s)\)\);" % (STR, STR), s)
    if m:
        return ("NodePtr contractsNode = std::make_shared<ConfigNode>(%s, std::string(%s));\n    root->AddNode(contractsNode);\n"
                "    ConfigNode* configNode = contractsNode.get();" % (m.group(1), m.group(2)))
    m = re.fullmatch(r"ConfigNode (\w+) = (\w+)\.AddNode\(new ConfigNode\((%s)(?:, (%s))?\)\);" % (STR, STR), s)
    if m:
        return "ConfigNode* %s = %s->AddNode(%s%s);" % (m.group(1), m.group(2), m.group(3), (", std::string(%s)" % m.group(4)) if m.group(4) else "")
    m = re.fullmatch(r"ConfigNode (\w+) = (\w+)\.AddNode\((%s)(?:, (%s))?\);" % (STR, STR), s)
    if m:
        return "ConfigNode* %s = %s->AddNode(%s%s);" % (m.group(1), m.group(2), m.group(3), (", std::string(%s)" % m.group(4)) if m.group(4) else "")
    m = re.fullmatch(r"ConfigNode (\w+) = new ConfigNode\((%s), (%s)\);" % (STR, STR), s)
    if m:
        return "NodePtr %s = std::make_shared<ConfigNode>(%s, std::string(%s));" % (m.group(1), m.group(2), m.group(3))
    m = re.fullmatch(r"(Add\w+)\((\w+)\);", s)
    if m:
        return "%s(%s);" % (m.group(1), m.group(2))
    m = re.fullmatch(r"(\w+)\.AddNode\((\w+)\);", s)
    if m:
        return "%s->AddNode(%s);" % (m.group(1), m.group(2))
    m = re.fullmatch(r"(\w+)\.AddValue\((%s), (.+), (%s)\);" % (STR, STR), s)
    if m:
        return "%s->AddValueWithComment(%s, %s, std::string(%s));" % (m.group(1), m.group(2), tr_expr(m.group(3)), m.group(4))
    m = re.fullmatch(r"(ConfigNode )?(\w+) = (\w+)\.GetNode\((%s)\);" % STR, s)
    if m:
        decl, var, src, nm = m.groups()
        if kind == "LoadConfig":
            sec, sub = node_path[src]
            name = nm.strip('"')
            node_path[var] = (name, "") if src == "config" else (sec, name)
        return "%s%s = %s;" % ("ConfigNode* " if decl else "", var, ("config->GetNode(%s)" % nm) if src == "config" else "%s->GetNode(%s)" % (src, nm))
    m = re.fullmatch(r"if \((\w+) != null\)", s)
    if m:
        return "if (%s != nullptr)" % m.group(1)
    if s == 'if (ExpansionsLoader.IsExpansionInstalled("Serenity"))':
        return 'if (SaveEnvironment::Current().IsExpansionInstalled("Serenity"))'
    if s == "{":
        depth_stack.append(serenity_block[0])
        return "{"
    if s == "}":
        serenity_block[0] = depth_stack.pop()
        return "}"
    m = re.fullmatch(r"config\.Save\(KSPUtil\.ApplicationRootPath \+ (%s)\);" % STR, s)
    if m:
        return "root->Save(applicationRootPath + %s);" % m.group(1)
    if s == "config = configNode;":
        return "config = contractsNode;"
    m = re.fullmatch(r"SystemUtilities\.LoadNode\((\w+), (%s), (%s), ref ([\w.]+), ([\w.]+)\);" % (STR, STR), s)
    if m:
        assert m.group(4) == m.group(5)
        var, path = m.group(1), m.group(4)
        if var == "config":
            sec, sub, nodecall = "", "", "config.get()"
        else:
            sec, sub = node_path[var]
            nodecall = var
        key = path.split(".")[-1]
        registry.append((sec, sub, key, path_cpp(path), serenity_block[0]))
        return "LoadNode(%s, %s, %s, %s, %s);" % (nodecall, m.group(2), m.group(3), path_cpp(path), path_cpp(path))
    raise SystemExit("untranslatable (%s): %s" % (kind, s))


def body(sig):
    i = find(sig)
    base = lines[i][: len(lines[i]) - len(lines[i].lstrip("\t"))]
    j = i + 1
    while lines[j] != base + "}":
        j += 1
    return i, lines[i + 2: j]


gen = []


def emit(sig, cpp_sig, kind, pre=()):
    i, stmts = body(sig)
    gen.append("// FinePrint/ContractDefs.cs:%d" % (i + 1))
    gen.append(cpp_sig + " {")
    for p in pre:
        gen.append("    " + p)
    depth = 1
    pending_serenity = False
    for st in stmts:
        s = st.strip()
        if not s:
            continue
        if s == 'if (ExpansionsLoader.IsExpansionInstalled("Serenity"))':
            pending_serenity = True
        t = tr_stmt(s, kind, None)
        if s == "{" and pending_serenity:
            serenity_block[0] = True
            pending_serenity = False
        if t == "}":
            depth -= 1
        gen.append("    " * depth + t)
        if t == "{":
            depth += 1
    gen.append("}")
    gen.append("")


emit("private static void CreateDefaultConfig()", "void ContractDefs::CreateDefaultConfig()", "CreateDefaultConfig",
     pre=["using NodePtr = ConfigNode::NodePtr;"])
emit("private static void AddSurveyDefinitions(ConfigNode surveyNode)", "void ContractDefs::AddSurveyDefinitions(ConfigNode* surveyNode)", "Add",
     pre=["using NodePtr = ConfigNode::NodePtr;"])
emit("private static void AddPartRequests(ConfigNode topNode)", "void ContractDefs::AddPartRequests(ConfigNode* topNode)", "Add",
     pre=["using NodePtr = ConfigNode::NodePtr;"])
emit("private static void AddResourceRequests(ConfigNode topNode)", "void ContractDefs::AddResourceRequests(ConfigNode* topNode)", "Add",
     pre=["using NodePtr = ConfigNode::NodePtr;"])
emit("private static void AddCrewRequests(ConfigNode topNode)", "void ContractDefs::AddCrewRequests(ConfigNode* topNode)", "Add",
     pre=["using NodePtr = ConfigNode::NodePtr;"])
emit("private static void LoadConfig()", "void ContractDefs::LoadConfig()", "LoadConfig")

gen.append("// C++ helper (no C# counterpart): the static initialisers of ContractDefs.cs:13-1337 and 1281-1337 as assignments, so a reload starts from the C# defaults.")
gen.append("void ContractDefs::ResetToDefaults() {")
for p, v in resets:
    gen.append("    %s = %s;" % (p, v))
gen.append("}")
gen.append("")
gen.append("// C++ helper: every value LoadConfig reads, as (cfg section node, sub node, key) -> member. Section and sub are the cfg node names")
gen.append("// (C# `Research` is the cfg node `Science`); `serenityOnly` entries are only read when Serenity is installed.")
gen.append("const std::vector<ContractDefs::Entry>& ContractDefs::Registry() {")
gen.append("    static const std::vector<Entry> entries = {")
for sec, sub, key, p, ser in registry:
    gen.append('        {"%s", "%s", "%s", &%s, %s},' % (sec, sub, key, p, "true" if ser else "false"))
gen.append("    };")
gen.append("    return entries;")
gen.append("}")
gen.append("")

gen.append("// C++ helper: every static member by its C# path (\"ARM.Expire.MinimumExpireDays\"), for the tests.")
gen.append("const std::vector<ContractDefs::Named>& ContractDefs::AllMembers() {")
gen.append("    static const std::vector<Named> all = {")
for p, v in resets:
    gen.append('        {"%s", &%s},' % (p.replace("::", "."), p))
gen.append("    };")
gen.append("    return all;")
gen.append("}")
gen.append("")

header = '''// GENERATED by tools/wp38c/gen_contract_defs.py from FinePrint/ContractDefs.cs (read only). Do not edit; regenerate.
// The mechanical part of FinePrint.ContractDefs: CreateDefaultConfig (the defaults writer), LoadConfig (the cfg reader), the Add*Requests /
// AddSurveyDefinitions node builders, and the registry that maps (cfg section, sub node, key) to the typed static member.
#include "ksp/fineprint/contract_defs.hpp"

#include <memory>

#include "ksp/contracts/fineprint_lite.hpp"
#include "ksp/save/save_environment.hpp"

namespace ksp::FinePrint {

using Contracts::Lite::LoadNode;

'''
open(os.path.join(core, "src", "fineprint", "contract_defs_gen.cpp"), "w", encoding="utf-8", newline="\n").write(
    header + "\n".join(gen) + "\n}  // namespace ksp::FinePrint\n")
print("members: %d fields, registry: %d entries (%d serenity), generated %d lines" % (len(resets), len(registry), sum(1 for r in registry if r[4]), len(gen)))
